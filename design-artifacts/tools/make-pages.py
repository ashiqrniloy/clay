def split_page(html):
    """(style, body markup without scripts, inline scripts) of a prototype page."""
    style = re.search(r"<style>(.*?)</style>", html, re.S)
    body = re.search(r"<body[^>]*>(.*)</body>", html, re.S).group(1)
    scripts = re.findall(r"<script>(.*?)</script>", body, re.S)
    body = re.sub(r"<script>.*?</script>", "", body, flags=re.S)
    return (style.group(1) if style else ""), body, "\n".join(scripts)


def drop_desk(body):
    """Replace the approved presentation backdrop with the review frame.

    The approved screens sit on a `desk` with film grain (a presentation device
    DESIGN.md §14 bans in the product). The pages show the app, so the desk and
    its grain go; the window itself is kept exactly as approved.
    """
    start = body.index('<div class="desk">')
    depth = 0
    for match in re.finditer(r"<(/?)([a-zA-Z][\w-]*)([^>]*?)(/?)>", body[start:]):
        name = match.group(2).lower()
        if name in VOID or match.group(4):
            continue
        if match.group(1):
            depth -= 1
            if depth == 0:
                return body[:start] + body[start + len('<div class="desk">'):start + match.start()] + body[start + match.end():]
        else:
            depth += 1
    raise SystemExit("could not find the end of the approved desk wrapper")


def derive(page, extra_css, extra_blocks):
    """The approved screen, verbatim, in a review frame, with extra states."""
    app = {"workspace": "workspace-rethink.html", "agent-landing": "agent-rethink.html"}[page]
    css, body, script = split_page((APPROVED / app).read_text())
    body = drop_desk(body)
    # the approved screens still advertise the two proposal-only palettes
    body = body.replace("six palettes, one geometry", "four shipped palettes, one geometry")
    if page == "agent-landing":
        body = patch_composer(body)
        body = patch_agent_head(body)
        body = patch_files_panel(body)
        # the footer's transport row needs a name for each of its two readings
        # so the disconnected scene can swap it (task 6 adds that scene)
        mcp = '<span class="faint">MCP</span>\n          <span>graft · 6 tools</span>'
        assert mcp in body, "the approved footer's MCP row moved"
        body = body.replace(
            mcp,
            '<span class="faint" data-foot-mcp>MCP</span>\n'
            "          <span data-foot-mcp>graft · 6 tools</span>"
            '<span data-foot-off>transport unavailable</span>',
            1,
        )
    for marker, block in extra_blocks:
        assert marker in body, marker
        body = body.replace(marker, marker + block, 1)
    body = retitlebar(body, page)
    return (
        "/* the approved %s screen, verbatim */\n%s\n%s"
        % (app.replace("-rethink.html", ""), css, extra_css),
        body,
        script,
    )


