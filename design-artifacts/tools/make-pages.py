def build(page):
    label = dict(PAGE_ORDER)[page]
    note = NOTES[page]
    data = '<script src="workspace-data.js"></script>\n' if page in DATA_PAGES else ""
    if page in DERIVED:
        css, body, script = DERIVED[page]()
        script = "<script>\n%s\n</script>" % script if script.strip() else ""
    else:
        css, body, script = AUTHORED[page]
        script = "<script>\n%s\n</script>" % script if script.strip() else ""
    body = annotate(body)
    bar = annotate(proto_bar(page, note))
    attrs = ""
    if page in SCENES:
        first = SCENES[page][0][0]
        attrs = ' data-scene="%s"' % first
        body = prime_scenes(body, first)
    return HEAD % {"label": label, "css": css, "bar": bar, "body": body, "data": data,
                   "script": script, "htmlattrs": attrs}


def prime_scenes(markup, first):
    """Mark every non-default scene hidden so the page is correct before JS runs."""
    def one(match):
        attrs = match.group(2)
        scene = re.search(r'data-scene="([^"]+)"', attrs).group(1)
        if scene == first or " hidden" in attrs:
            return match.group(0)
        return "<%s%s hidden>" % (match.group(1), attrs)
    return re.sub(r"<([a-zA-Z][\w-]*)((?:\s[^>]*?)?data-scene=[^>]*?)>", one, markup)


