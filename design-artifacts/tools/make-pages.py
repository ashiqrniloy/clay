def check(html, page, keys):
    """Contract checks that must hold for every page."""
    problems = []
    # scripts build markup as strings: only real elements are checked
    markup = re.sub(r"<script>.*?</script>", "", html, flags=re.S)
    markup = re.sub(r"<style>.*?</style>", "", markup, flags=re.S)
    used = set(re.findall(r'data-clay-ds="([^"]+)"', markup))
    unknown = sorted(used - keys)
    if unknown:
        problems.append("%s: recipe keys no package declares: %s" % (page, unknown))
    # every element that mirrors a component must carry its key
    bare = []
    for match in re.finditer(r"<([a-zA-Z][\w-]*)((?:\s[^>]*?)?)>", markup):
        attrs = match.group(2)
        if "data-clay-ds" in attrs or "class=" not in attrs:
            continue
        classes = re.search(r'class="([^"]*)"', attrs).group(1).split()
        for token, key in CLASS_KEYS:
            if token in classes:
                bare.append(token)
                break
    if bare:
        problems.append("%s: %d component element(s) without data-clay-ds: %s" % (page, len(bare), sorted(set(bare))))
    if 'src="http' in html or "http://" in html.replace("http://www.w3.org", ""):
        problems.append("%s: external reference" % page)
    for asset in ("theme.css", "ds-quiet.css", "components.css", "pages.css", "ds.js"):
        if asset not in html:
            problems.append("%s: missing %s" % (page, asset))
    if page in SCENES and page not in JS_SCENES:
        for sid, _ in SCENES[page]:
            if 'data-scene="%s"' % sid not in html:
                problems.append("%s: scene %s missing" % (page, sid))
    return problems


def main():
    if RECORD:
        record_recents()
        return 0
    keys = contract_keys()
    problems = []
    written = []
    # PAGE_ORDER also carries pages built by another generator (the theme board,
    # tools/make-theme-values.py) so the nav is identical on every page.
    for page in NOTES:
        html = build(page)
        problems += check(html, page, keys)
        target = PROTO / (page + ".html")
        if CHECK:
            current = target.read_text() if target.exists() else ""
            if current != html:
                problems.append("%s.html is out of date — run make-pages.py" % page)
        else:
            target.write_text(html)
        written.append((page, len(html)))
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    verb = "verified" if CHECK else "wrote"
    for page, size in written:
        print("%s %s.html (%.1f kB)" % (verb, page, size / 1024))
    return 0


