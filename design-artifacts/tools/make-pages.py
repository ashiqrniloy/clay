def annotate(markup, seen=None):
    """Add `data-clay-ds="<recipe key>"` to every element that mirrors a component."""
    def one(match):
        tag, attrs = match.group(1), match.group(2)
        if "data-clay-ds" in attrs:
            return match.group(0)
        classes = re.search(r'class="([^"]*)"', attrs)
        if not classes:
            return match.group(0)
        tokens = classes.group(1).split()
        for token, key in CLASS_KEYS:
            if token in tokens:
                return "<%s%s data-clay-ds=\"%s\">" % (tag, attrs, key)
        return match.group(0)
    return re.sub(r"<([a-zA-Z][\w-]*)((?:\s[^>]*?)?)>", one, markup)


