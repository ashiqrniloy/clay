def package_facts():
    """Every bundled root and helper, straight from the inventory and manifests."""
    inventory = (REPO / "src" / "packages" / "bundled-inventory.toml").read_text()
    roots = re.findall(r'^root = "([^"]+)"', inventory, re.M)
    helpers = re.findall(r'^helper = "([^"]+)"', inventory, re.M)
    facts = []
    for root, kind in [(r, "root") for r in roots] + [(h, "helper") for h in helpers]:
        manifest = REPO / "packages" / root / "package.json"
        if not manifest.exists():
            continue
        data = json.loads(manifest.read_text())
        contributions = data.get("clay", {}).get("contributions", {})
        facts.append({
            "root": root,
            "name": data.get("name", root),
            "version": data.get("version", "—"),
            "kind": kind,
            "contributes": sorted(contributions.keys()),
        })
    return facts


def package_files(root, depth=2):
    """The files a package ships, minus build output nobody reviews."""
    base = REPO / "packages" / root
    out = []
    for path in sorted(base.rglob("*")):
        rel = path.relative_to(base)
        if len(rel.parts) > depth or any(part in ("node_modules", ".git") for part in rel.parts):
            continue
        if path.is_dir():
            continue
        out.append(str(rel))
    return out


def recents():
    """The launcher's recent workspaces and agent types.

    These are the user's own machine state, so they come from a recorded fixture
    (`start-recents.json`, provenance inside it) rather than from discovery at
    build time: the checked-in artifact must build identically on every machine,
    and the prototype must not invent a recents list it cannot verify.
    """
    data = json.loads((PROTO / "start-recents.json").read_text())
    return data["workspaces"], data["agents"]


def record_recents():
    """Re-record `start-recents.json` from this machine (`--recents`)."""
    root = pathlib.Path.home() / "Projects"
    workspaces = []
    if root.is_dir():
        for d in sorted(root.iterdir()):
            if not (d / ".git").exists():
                continue
            branch = subprocess.run(
                ["git", "-C", str(d), "rev-parse", "--abbrev-ref", "HEAD"],
                capture_output=True, text=True,
            ).stdout.strip() or "unknown"
            workspaces.append({"name": d.name, "path": str(d), "branch": branch,
                               "mcp": 1 if (d / ".mcp.json").exists() else 0})
    agents = []
    aroot = pathlib.Path.home() / ".clay" / "agents"
    if aroot.is_dir():
        for d in sorted(aroot.iterdir()):
            if not d.is_dir():
                continue
            skills = d / "skills"
            mcp = d / "mcp.json"
            servers = 0
            if mcp.exists():
                try:
                    servers = len(json.loads(mcp.read_text()).get("servers", {}))
                except ValueError:
                    servers = 0
            agents.append({"id": d.name, "label": d.name.replace("-", " ").title(),
                           "skills": len(list(skills.iterdir())) if skills.is_dir() else 0,
                           "mcp": servers})
    path = PROTO / "start-recents.json"
    previous = json.loads(path.read_text())
    previous["workspaces"], previous["agents"] = workspaces, agents
    path.write_text(json.dumps(previous, indent=2) + "\n")
    print("recorded %d workspace(s), %d agent type(s) into start-recents.json" % (len(workspaces), len(agents)))


